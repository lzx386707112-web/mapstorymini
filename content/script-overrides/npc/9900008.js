// 一行两格：按显示宽度补空格对齐。不用制表符——全角字符下 \t 会把整行撑爆。
function 菜单行(条目列表) {
    var 行 = "";
    for (var n = 0; n < 条目列表.length; n++) {
        行 += "#L" + 条目列表[n][0] + "##b[" + 条目列表[n][1] + "]#k#l";
        if (n < 条目列表.length - 1) {
            var 补 = 24 - 取显示宽("[" + 条目列表[n][1] + "]");
            行 += " ".repeat(补 > 0 ? 补 : 1);
        }
    }
    return 行 + "\r\n";
}

// 1 个汉字/全角符号算 2，其余算 1
function 取显示宽(文本) {
    var 宽 = 0;
    for (var i = 0; i < 文本.length; i++) {
        宽 += 文本.charCodeAt(i) > 0xFF ? 2 : 1;
    }
    return 宽;
}


function start() {
    // 引擎实例可能复用，显式重置，不依赖变量初值
    已打开 = false;
    action(1, 0, 0);
}

function action(mode, type, selection) {
    if (mode !== 1) {
        cm.dispose();
        return;
    }
    if (!已打开) {
        已打开 = true;
        显示主菜单();
        return;
    }
    if (selection === 0) {
        显示主菜单();
        return;
    }
    // 100=五转 101=六转 102=我的进度 103=怎么去 104=技能面板
    if (selection >= 100 && selection <= 104) {
        显示主题(selection - 100);
        return;
    }
    cm.dispose();
}


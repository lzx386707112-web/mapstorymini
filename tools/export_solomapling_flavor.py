#!/usr/bin/env python3
"""Copy the original Java market dialogue pools into C# without changing lines."""
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent.parent / "BeiDou-Server/gms-server/src/main/java/soloMapling/FreeMarket/MarketBotFlavor.java"
TARGET = ROOT / "Assets/Scripts/Server/Bot/Social/MarketBotFlavor.Data.cs"


def main():
    raw = SOURCE.read_bytes()
    source = raw.decode("utf-8-sig")
    pools = []
    for match in re.finditer(r"private static final String\[\]\s+(\w+)\s*=\s*\{(.*?)\};", source, re.S):
        values = json.loads("[" + match[2] + "]")
        pools.append((match[1], values))
    expected = {"SELL_PREFIX", "SELL_SUFFIX", "BUY_PREFIX", "BUY_SUFFIX", "WANDER", "BROWSE", "IDLE", "CHAT", "REPLY", "MEGA", "TRADE_OPEN", "TRADE_REPLY", "FUNNY", "BEG", "WARN", "SCAM"}
    if {name for name, _ in pools} != expected:
        raise ValueError("Original market dialogue pool structure changed")
    lines = ["// Generated by tools/export_solomapling_flavor.py; do not edit dialogue.",
             "// Source SHA256: " + hashlib.sha256(raw).hexdigest(),
             "namespace Server.Bot.Social", "{", "    public sealed partial class MarketBotFlavor", "    {"]
    for name, values in pools:
        lines.append("        static readonly string[] " + name + " = {")
        lines.extend("            " + json.dumps(v, ensure_ascii=False) + "," for v in values)
        lines.append("        };")
    lines.extend(["    }", "}"])
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Copied {len(pools)} original market dialogue pools, {sum(len(v) for _, v in pools)} strings")


if __name__ == "__main__":
    main()
